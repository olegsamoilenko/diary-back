// Build-time projection of the mobile UI catalog; no sibling-repo runtime dependency.
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const root = path.resolve(__dirname, '..');
  const source = path.resolve(root, '../diary-front/locales');
  const keys = {
    planner: 'today.stream.ui.navigation.goals',
    today: 'today.stream.ui.navigation.today',
    calendar: 'today.stream.ui.navigation.calendar',
    conversations: 'today.stream.ui.navigation.conversations',
    settings: 'today.stream.ui.navigation.settings',
    help: 'help.title',
    edit: 'common.edit',
    delete: 'common.delete',
    archive: 'goals.toTheArchive',
    finishHabit: 'plannerArchive.finishHabit',
    cancelReminder: 'today.cards.reminderCancel',
    single: 'plannerSeries.single',
    following: 'plannerSeries.following',
    series: 'plannerSeries.series',
    addEntry: 'entryLinks.add',
    linkTo: 'entryLinks.attach',
    mark: 'goals.mark',
  };
  const locales = fs
    .readdirSync(source)
    .filter((locale) =>
      fs.existsSync(path.join(source, locale, 'translation.json')),
    )
    .sort();
  const labels = Object.fromEntries(
    locales.map((locale) => {
      const catalog = JSON.parse(
        fs.readFileSync(path.join(source, locale, 'translation.json'), 'utf8'),
      );
      return [
        locale,
        Object.fromEntries(
          Object.entries(keys).map(([name, key]) => {
            const value = key
              .split('.')
              .reduce((value, part) => value?.[part], catalog);
            if (
              typeof value !== 'string' ||
              !value.trim() ||
              value.includes('{{')
            )
              throw Error(`Missing static UI label: ${locale}:${key}`);
            return [name, value];
          }),
        ),
      ];
    }),
  );
  const raw =
    '// Generated by scripts/sync-ai-ui-labels.cjs from diary-front/locales. Do not edit.\n' +
    `export const NEMORY_UI_LABELS = ${JSON.stringify(labels, null, 2)} as const;\n`;
  const target = path.join(root, 'src/ai/utils/nemory-ui-labels.generated.ts');
  const prettier = require('prettier');
  const output = await prettier.format(raw, {
    ...(await prettier.resolveConfig(target)),
    parser: 'typescript',
  });
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output)
      throw Error(
        'AI UI labels are stale: run node scripts/sync-ai-ui-labels.cjs',
      );
  } else fs.writeFileSync(target, output);
  console.log(
    `AI UI labels: ${locales.join(', ')}; ${Object.keys(keys).length} keys; ${process.argv.includes('--check') ? 'verified' : 'generated'}`,
  );
})().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
